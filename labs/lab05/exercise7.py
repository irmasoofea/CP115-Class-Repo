import math
from math import sqrt, pow, sin, cos
square_root = int(sqrt(25))
power_result = int(pow(2, 3))
number = int(input("Enter a number: "))
sine_number = int(sin(number))

print("Square root of number:", number, "is", square_root)
print("Power result:", power_result)
print("Sine of number:", number, "is", sine_number)